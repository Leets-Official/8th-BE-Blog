CREATE TABLE IF NOT EXISTS search_keywords (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    normalized_keyword VARCHAR(100) NOT NULL UNIQUE,
    suggestible BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS search_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keyword_id BIGINT NOT NULL REFERENCES search_keywords(id),
    searched_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_search_event_keyword_time ON search_events(keyword_id, searched_at);
CREATE INDEX IF NOT EXISTS idx_search_event_time_keyword ON search_events(searched_at, keyword_id);
CREATE TABLE IF NOT EXISTS search_dedup_states (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keyword_id BIGINT NOT NULL REFERENCES search_keywords(id),
    session_key VARCHAR(100) NOT NULL,
    last_counted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(keyword_id, session_key)
);
CREATE TABLE IF NOT EXISTS search_keyword_buckets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keyword_id BIGINT NOT NULL REFERENCES search_keywords(id),
    bucket_start TIMESTAMP WITH TIME ZONE NOT NULL,
    search_count BIGINT NOT NULL CHECK (search_count >= 0),
    UNIQUE(keyword_id, bucket_start)
);
CREATE INDEX IF NOT EXISTS idx_search_bucket_time_keyword ON search_keyword_buckets(bucket_start, keyword_id);
